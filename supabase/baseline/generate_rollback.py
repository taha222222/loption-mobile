"""Generate the Phase 1C rollback script (storage + core, ONE transaction).

For each migration, every policy it drops on a pre-existing table is
restored VERBATIM from the staging evidence (the same text the baseline
uses) and every policy it creates there is dropped. Both lists are parsed
from the migration file itself, so a rollback cannot drift from its
migration.

Output:
  supabase/rollback/phase1c_rollback.sql
    storage part first, then core part, in one BEGIN ... COMMIT with a
    role check, a preflight, a postcondition and a deferred commit gate.
    It is run ONLY by supabase/rollback/phase1c_rollback.sh (the supported
    procedure), which supplies the psql variables it requires.
"""
