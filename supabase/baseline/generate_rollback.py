def evidence_policy_md5(policies: list, schema: str) -> str:
    """md5 exactly as preflight_staging_readonly.sql computes it on the live catalog."""
    rows = sorted((p for p in policies if p["schema"] == schema),
                  key=lambda p: (p["table"].encode(), p["name"].encode()))   # collate "C"
    text = "\n".join("|".join([p["table"], p["name"], p["command"], ",".join(p["roles"]),
                               p["using"] or "", p["with_check"] or ""]) for p in rows)
    return hashlib.md5(text.encode()).hexdigest()


def main() -> int:
    ev = json.loads(EVIDENCE.read_text())
    evidence = {(p["schema"], p["table"], p["name"]): p for p in ev["policies"]}
    tables = sorted(t["table"] for t in ev["tables"] if t["schema"] == "public")
    pub_funcs = [f for f in ev["functions"] if f["schema"] == "public"]
    missing = sorted(set(PRESERVED) - set(tables))
    if missing:
        raise SystemExit(f"preserved tables not in the evidence: {missing}")
    s_drop, s_new = policy_changes((ROOT / f"supabase/migrations/{STORAGE}.sql").read_text(), evidence)
    c_drop, c_new = policy_changes((ROOT / f"supabase/migrations/{CORE}.sql").read_text(), evidence)

    storage_sql = []
    for k in s_new:
        storage_sql.append("  " + drop_line(k))
    for k in s_drop:
        storage_sql.append("  " + drop_line(k))
        storage_sql.append("  execute $p$" + policy_sql(evidence[k])[:-1] + "$p$;")
    header = (HEADER.replace("@STORAGE@", STORAGE).replace("@CORE@", CORE)
              .replace("@STORAGE_POLICY_NAMES@", ", ".join("'" + k[2] + "'" for k in s_new))
              .replace("@PRESERVED@", ", ".join("'" + t + "'" for t in PRESERVED))
              .replace("@STORAGE_POLICY_SQL@", "\n".join(storage_sql)))
    o = [header.rstrip("\n")]
    o += [drop_line(k) for k in c_new]
    o.append("")
    o.append("-- 3. Restore the staging policies the migration dropped (verbatim from evidence).")
    for k in c_drop:
        o.append(drop_line(k))
        o.append(policy_sql(evidence[k]))
    o.append(MIDDLE.rstrip("\n"))
    o.append("grant all on " + ", ".join("public." + ident(t) for t in tables) + " to anon, authenticated;")
    o.append("")
    o.append("-- 6. Function privileges and configuration as observed.")
    for f in pub_funcs:
        # identity arguments are "name type, ..." (single-word types in the evidence)
        arg_types = [a.split()[-1] for a in f["args"].split(",") if a.strip()]
        sig = f"public.{f['name']}({', '.join(arg_types)})"
        o.append(f"grant execute on function {sig} to public, anon, authenticated;")
        if f["config"] is None:
            o.append(f"alter function {sig} reset all;")
    o.append(FOOTER.replace("@PUBLIC_POLICY_MD5@", evidence_policy_md5(ev["policies"], "public"))
                   .replace("@STORAGE_POLICY_MD5@", evidence_policy_md5(ev["policies"], "storage")).rstrip("\n"))
    (ROOT / "supabase/rollback/phase1c_rollback.sql").write_text("\n".join(o) + "\n")
    print(f"wrote supabase/rollback/phase1c_rollback.sql: storage part restores {len(s_drop)} policies, drops {len(s_new)}; "
          f"core part restores {len(c_drop)} policies, drops {len(c_new)}")
    return 0


