#!/usr/bin/env python3
"""Generate the Phase 1C rollback scripts (core + storage).

For each migration, every policy it drops on a pre-existing table is
restored VERBATIM from the staging evidence (the same text the baseline
uses) and every policy it creates there is dropped. Both lists are parsed
from the migration file itself, so a rollback cannot drift from its
migration.

Outputs:
  supabase/rollback/20261016171000_phase1c_storage_meal_images.down.sql   (run FIRST)
  supabase/rollback/20261016170000_phase1c_security_containment.down.sql  (run SECOND)
"""
import json
import pathlib
import re
import sys

ROOT = pathlib.Path(__file__).resolve().parents[2]
EVIDENCE = ROOT / "supabase/evidence/catalog_2026-10-15.json"
CORE = "20261016170000_phase1c_security_containment"
STORAGE = "20261016171000_phase1c_storage_meal_images"
NEW_TABLES = {("public", "kitchens"), ("public", "staff_roles"), ("public", "security_audit_log")}

POLICY_RE = (r'(?:"([^"]+)"|([A-Za-z_][A-Za-z0-9_]*))\s+on\s+'
             r'(public|storage)\.([A-Za-z_][A-Za-z0-9_]*)')


def ident(name: str) -> str:
    return '"' + name.replace('"', '""') + '"'


def policy_sql(p: dict) -> str:
    s = (f"create policy {ident(p['name'])} on {p['schema']}.{ident(p['table'])} "
         f"as {p['permissive'].lower()} for {p['command'].lower()} to {', '.join(p['roles'])}")
    if p["using"] is not None:
        s += f"\n  using ({p['using']})"
    if p["with_check"] is not None:
        s += f"\n  with check ({p['with_check']})"
    return s + ";"


def policy_changes(migration_text: str, evidence: dict):
    """Return (dropped evidence policies, created policies on existing tables)."""
    dropped, created = [], []
    for m in re.finditer(r"drop policy if exists\s+" + POLICY_RE, migration_text):
        key = (m.group(3), m.group(4), m.group(1) or m.group(2))
        if key in evidence and key not in dropped:
            dropped.append(key)
    for m in re.finditer(r"create policy\s+" + POLICY_RE, migration_text):
        key = (m.group(3), m.group(4), m.group(1) or m.group(2))
        if (key[0], key[1]) not in NEW_TABLES and key not in created:
            created.append(key)
    clash = [k for k in created if k in evidence]
    if clash:
        raise SystemExit(f"migration re-creates evidence policy names {clash}; extend generator")
    return dropped, created


def drop_line(k) -> str:
    return f"drop policy if exists {ident(k[2])} on {k[0]}.{ident(k[1])};"


def main() -> int:
    ev = json.loads(EVIDENCE.read_text())
    evidence = {(p["schema"], p["table"], p["name"]): p for p in ev["policies"]}
    tables = sorted(t["table"] for t in ev["tables"] if t["schema"] == "public")
    pub_funcs = [f for f in ev["functions"] if f["schema"] == "public"]

    # ------------------------------------------------------------ storage
    s_drop, s_new = policy_changes((ROOT / f"supabase/migrations/{STORAGE}.sql").read_text(), evidence)
    o = [f"""-- =====================================================================
-- ROLLBACK for {STORAGE}.sql
-- GENERATED by supabase/baseline/generate_rollback.py. DO NOT EDIT BY HAND.
--
-- !!! DANGER: RE-OPENS UPLOADS BY ANY SIGNED-IN USER INTO THE PUBLIC
-- !!! meal-images BUCKET (staging policies of 2026-10-15, verbatim).
-- Run this FIRST (before the core rollback), in ONE transaction, only if
-- the CTO approves. Prefer forward recovery (plan section "Recovery").
-- No object row is changed. The meal-images bucket limits are restored
-- EXACTLY to the values recorded by the migration in security_audit_log
-- (SQL NULL where the recorded old value is JSON null). If the migration
-- recorded no change (the bucket was already in the approved state),
-- the bucket is left as it is.
-- =====================================================================

set lock_timeout = '10s';

do $bucket$
declare
  rec jsonb;
begin
  if to_regclass('public.security_audit_log') is null then
    raise exception 'security_audit_log missing: cannot restore the recorded bucket settings (run this before the core rollback)';
  end if;
  select l.details into rec
    from public.security_audit_log l
   where l.action = 'storage.bucket.limits_set' and l.details ->> 'bucket' = 'meal-images'
   order by l.id desc limit 1;
  if rec is null then
    raise notice 'no recorded bucket change: meal-images settings left unchanged';
    return;
  end if;
  update storage.buckets
     set file_size_limit = (rec ->> 'old_file_size_limit')::bigint,
         allowed_mime_types = case when jsonb_typeof(rec -> 'old_allowed_mime_types') = 'array'
                                   then array(select jsonb_array_elements_text(rec -> 'old_allowed_mime_types'))
                                   else null end
   where id = 'meal-images';
end
$bucket$;
"""]
    o += [drop_line(k) for k in s_new]
    o.append("")
    for k in s_drop:
        o.append(drop_line(k))
        o.append(policy_sql(evidence[k]))
    o.append("\nreset lock_timeout;")
    (ROOT / f"supabase/rollback/{STORAGE}.down.sql").write_text("\n".join(o) + "\n")
    print(f"wrote supabase/rollback/{STORAGE}.down.sql: restores {len(s_drop)} policies, drops {len(s_new)}")

    # ------------------------------------------------------------ core
    c_drop, c_new = policy_changes((ROOT / f"supabase/migrations/{CORE}.sql").read_text(), evidence)
    o = [f"""-- =====================================================================
-- ROLLBACK for {CORE}.sql
-- GENERATED by supabase/baseline/generate_rollback.py. DO NOT EDIT BY HAND.
--
-- !!! DANGER: THIS RE-OPENS CRITICAL VULNERABILITIES C1-C4 AND H2-H4 !!!
-- It restores, verbatim, the staging policies and grants of 2026-10-15:
-- anyone (including anonymous callers) can create and rewrite orders with
-- any price, payment method and status; any customer can make themselves
-- an administrator; anonymous callers can read, change and delete
-- daily_closings; drivers can approve themselves; partners can rewrite
-- their revenue shares.
--
-- Do NOT use this as a routine undo. Use the forward-recovery procedure in
-- docs/v1/PHASE1C_DATABASE_SECURITY_PLAN.md (section "Recovery") first.
-- Only if staging is unusable AND the CTO approves: run the STORAGE
-- rollback first, then this file, each in ONE transaction, then re-apply
-- the containment migrations as soon as possible.
--
-- Data: no existing order, profile, payment, kiosk or closing row is
-- changed. It DROPS the new tables kitchens, staff_roles and
-- security_audit_log. EXPORT THEM FIRST (they hold role grants and the
-- audit trail):
--   copy (select * from public.staff_roles)        to stdout with csv header;
--   copy (select * from public.security_audit_log) to stdout with csv header;
--   copy (select * from public.kitchens)           to stdout with csv header;
-- Driver availability: drivers that the migration set offline get their
-- previous drivers.status back from security_audit_log, but only if they
-- are still 'offline' (a later change is not overwritten).
-- =====================================================================

set lock_timeout = '10s';

do $order$
begin
  if exists (select 1 from pg_policies where schemaname = 'storage'
              and policyname in ({", ".join("'" + k[2] + "'" for k in s_new)})) then
    raise exception 'run supabase/rollback/{STORAGE}.down.sql first (storage policies depend on has_staff_role)';
  end if;
end
$order$;

-- 1. Driver availability: remove the invariant, restore legacy values.
drop trigger if exists trg_enforce_driver_availability on public.drivers;
alter table public.drivers drop constraint if exists drivers_status_availability_check;
do $restore$
begin
  if to_regclass('public.security_audit_log') is not null then
    update public.drivers d
       set status = x.old_status
      from (select distinct on (target_user_id) target_user_id, details ->> 'old_status' as old_status
              from public.security_audit_log
             where action = 'drivers.status.normalised'
             order by target_user_id, id desc) x
     where d.id = x.target_user_id and d.status = 'offline';
  end if;
end
$restore$;

-- 2. Drop the policies the migration created on existing tables."""]
    o += [drop_line(k) for k in c_new]
    o.append("")
    o.append("-- 3. Restore the staging policies the migration dropped (verbatim from evidence).")
    for k in c_drop:
        o.append(drop_line(k))
        o.append(policy_sql(evidence[k]))
    o.append("""
-- 4. user_profiles guard.
drop trigger if exists trg_enforce_profile_privilege_guard on public.user_profiles;
drop function if exists public.enforce_profile_privilege_guard();

-- 5. Client grants exactly as observed (full table privileges for anon and
--    authenticated on every pre-existing public table, no column ACLs).
revoke update (gender, goal, height, weight, age, activity_level, program, phone, full_name, updated_at)
  on public.user_profiles from authenticated;
revoke update (first_name, last_name, phone, current_latitude, current_longitude, last_location_update, updated_at)
  on public.drivers from authenticated;""")
    o.append("grant all on " + ", ".join("public." + ident(t) for t in tables) + " to anon, authenticated;")
    o.append("")
    o.append("-- 6. Function privileges and configuration as observed.")
    for f in pub_funcs:
        # identity arguments are "name type, ..." (single-word types in the evidence)
        arg_types = [a.split()[-1] for a in f["args"].split(",") if a.strip()]
        sig = f"public.{f['name']}({', '.join(arg_types)})"
        o.append(f"grant execute on function {sig} to public, anon, authenticated;")
        if f["config"] is None:
            o.append(f"alter function {sig} reset all;")
    o.append("""
-- 7. New functions and tables.
drop function if exists public.containment_violations();
drop function if exists public.set_driver_availability(boolean);
drop function if exists public.enforce_driver_availability();
drop function if exists public.assign_staff_role(uuid, text, uuid);
drop function if exists public.revoke_staff_role(uuid, text, uuid);
drop table if exists public.security_audit_log;
drop function if exists public.security_audit_log_append_only();
drop table if exists public.staff_roles;
drop function if exists public.has_staff_role(text);
drop table if exists public.kitchens;

-- 8. Default privileges back to the observed Supabase defaults.
alter default privileges in schema public grant all on tables    to anon, authenticated;
alter default privileges in schema public grant all on sequences to anon, authenticated;
alter default privileges in schema public grant all on functions to anon, authenticated;
alter default privileges grant execute on functions to public;

reset lock_timeout;""")
    (ROOT / f"supabase/rollback/{CORE}.down.sql").write_text("\n".join(o) + "\n")
    print(f"wrote supabase/rollback/{CORE}.down.sql: restores {len(c_drop)} policies, drops {len(c_new)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
