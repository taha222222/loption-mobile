NEW_TABLES = {("public", "kitchens"), ("public", "staff_roles"), ("public", "security_audit_log")}

POLICY_RE = (r'(?:"([^"]+)"|([A-Za-z_][A-Za-z0-9_]*))\s+on\s+'
             r'(public|storage)\.([A-Za-z_][A-Za-z0-9_]*)')


def ident(name: str) -> str:
    return '"' + name.replace('"', '""') + '"'


def policy_sql(p: dict) -> str:
    s = (f"create policy {ident(p['name'])} on {p['schema']}.{ident(p['table'])} "
         f"as {p['permissive'].lower()} for {p['command'].lower()} to {', '.join(p['roles'])}")
    if p["using"] is not None:
        s += f"\n  using ({p['using']})"
    if p["with_check"] is not None:
        s += f"\n  with check ({p['with_check']})"
    return s + ";"


def policy_changes(migration_text: str, evidence: dict):
    """Return (dropped evidence policies, created policies on existing tables)."""
    dropped, created = [], []
    for m in re.finditer(r"drop policy if exists\s+" + POLICY_RE, migration_text):
        key = (m.group(3), m.group(4), m.group(1) or m.group(2))
        if key in evidence and key not in dropped:
            dropped.append(key)
    for m in re.finditer(r"create policy\s+" + POLICY_RE, migration_text):
        key = (m.group(3), m.group(4), m.group(1) or m.group(2))
        if (key[0], key[1]) not in NEW_TABLES and key not in created:
            created.append(key)
    clash = [k for k in created if k in evidence]
    if clash:
        raise SystemExit(f"migration re-creates evidence policy names {clash}; extend generator")
    return dropped, created


def drop_line(k) -> str:
    return f"drop policy if exists {ident(k[2])} on {k[0]}.{ident(k[1])};"


