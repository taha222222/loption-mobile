#!/usr/bin/env python3
"""Generate the schema-only baseline migration from the staging catalog export.

Input:  supabase/evidence/catalog_2026-10-15.json (owner-run, read-only catalog
        query; see supabase/evidence/README.md for provenance).
Output: supabase/baseline/staging_schema_2026-10-15.sql
        (deliberately NOT under supabase/migrations/, so `supabase db push`
        can never execute it against the existing staging project)

Deterministic: the same input always yields byte-identical output, so a
reviewer can re-run this script and `git diff` the result.

Only objects present in the evidence are emitted. Everything is copied
verbatim from catalog text (pg_get_constraintdef, pg_indexes.indexdef,
pg_policies, pg_get_functiondef, pg_get_triggerdef); nothing is inferred
except the mapping from information_schema type names to DDL type names.

Not emitted, because the evidence does not contain it or it is managed by
the Supabase platform (see the header written into the output):
  * numeric precision/scale and varchar lengths (not captured by the query);
  * storage schema tables, functions and triggers (platform-managed);
  * event triggers (e.g. whether rls_auto_enable() is attached) and
    Auth hooks (not captured);
  * table data, sequences, comments, ownership other than the migration role.
"""
import json
import pathlib
import sys

ROOT = pathlib.Path(__file__).resolve().parents[2]
SRC = ROOT / "supabase/evidence/catalog_2026-10-15.json"
DST = ROOT / "supabase/baseline/staging_schema_2026-10-15.sql"

TYPE_MAP = {
    "text": "text", "numeric": "numeric", "uuid": "uuid",
    "timestamp": "timestamp without time zone",
    "timestamptz": "timestamp with time zone",
    "int4": "integer", "bool": "boolean", "date": "date", "jsonb": "jsonb",
}
# Constraint creation order: PK, unique, check before foreign keys.
CON_ORDER = {"p": 0, "u": 1, "c": 2, "f": 3}


def ident(name: str) -> str:
    return '"' + name.replace('"', '""') + '"'


def main() -> int:
    ev = json.loads(SRC.read_text())
    out: list[str] = []
    w = out.append

    w("-- =====================================================================")
    w("-- BASELINE: staging schema (public) as captured on " + ev["generated_at"])
    w("-- PostgreSQL " + ev["server_version"] + ". GENERATED by supabase/baseline/generate_baseline.py")
    w("-- from supabase/evidence/catalog_2026-10-15.json. DO NOT EDIT BY HAND.")
    w("--")
    w("-- TEST FIXTURE, NOT A MIGRATION. It rebuilds the pre-Phase-1C staging")
    w("-- public schema on a CLEAN, DISPOSABLE database. It lives outside")
    w("-- supabase/migrations/ so `supabase db push` never runs it, and it")
    w("-- refuses to run on a database that already has this schema.")
    w("--")
    w("-- It intentionally reproduces the INSECURE staging policies (C1-C4,")
    w("-- H2-H4) so that the containment migrations can be tested against them.")
    w("--")
    w("-- It is a reconstruction that is faithful ONLY in the dimensions the")
    w("-- catalog query captured; it is NOT a complete clone of staging. Exact")
    w("-- comparison scope and omissions: supabase/evidence/README.md.")
    w("-- =====================================================================")
    w("")
    w("do $guard$")
    w("begin")
    w("  if to_regclass('public.orders') is not null or to_regclass('public.user_profiles') is not null then")
    w("    raise exception 'staging_schema baseline: refusing to run on a database that already has the schema (test fixture only)';")
    w("  end if;")
    w("end")
    w("$guard$;")
    w("")
    w("set check_function_bodies = off;")
    w("set search_path = public, extensions;")
    w("")
    for ext in sorted(e["name"] for e in ev["extensions"]):
        if ext in ("uuid-ossp", "pgcrypto"):
            w(f"create extension if not exists {ident(ext)} with schema extensions;")
    w("")

    # ---- tables and columns
    cols: dict[str, list] = {}
    for c in ev["columns"]:
        cols.setdefault(c["table"], []).append(c)
    pub_tables = [t["table"] for t in ev["tables"] if t["schema"] == "public"]
    for t in pub_tables:
        defs = []
        for c in sorted(cols[t], key=lambda c: c["pos"]):
            typ = TYPE_MAP[c["udt"]]
            line = f"  {ident(c['column'])} {typ}"
            if c["default"] is not None:
                line += f" default {c['default']}"
            if c["nullable"] == "NO":
                line += " not null"
            defs.append(line)
        w(f"create table public.{ident(t)} (\n" + ",\n".join(defs) + "\n);")
    w("")

    # ---- constraints (verbatim definitions)
    cons = sorted(ev["constraints"], key=lambda c: (CON_ORDER[c["type"]], c["table"], c["name"]))
    con_names = set()
    for c in cons:
        table = c["table"] if c["table"].startswith("public.") else "public." + c["table"]
        con_names.add(c["name"])
        w(f"alter table {table} add constraint {ident(c['name'])} {c['definition']};")
    w("")

    # ---- indexes not created by a constraint
    for i in sorted(ev["indexes"], key=lambda i: (i["table"], i["name"])):
        if i["name"] in con_names:
            continue
        w(i["definition"] + ";")
    w("")

    # ---- RLS flags
    for t in ev["tables"]:
        if t["schema"] != "public":
            continue
        if t["rls_enabled"]:
            w(f"alter table public.{ident(t['table'])} enable row level security;")
        if t["rls_forced"]:
            w(f"alter table public.{ident(t['table'])} force row level security;")
    w("")

    # ---- client grants as observed (effective privileges were full on every
    # public table for anon and authenticated; Supabase default privileges
    # already grant this on creation, made explicit here for determinism).
    full = all(p["select"] and p["insert"] and p["update"] and p["delete"]
               for p in ev["effective_table_privileges"] if p["schema"] == "public")
    if not full:
        print("evidence shows non-uniform public grants; generator needs extending", file=sys.stderr)
        return 1
    w("grant all on all tables in schema public to anon, authenticated, service_role;")
    w("")

    # ---- functions in public (verbatim)
    for f in ev["functions"]:
        if f["schema"] != "public":
            continue
        w(f["definition"].rstrip() + ";")
        w("")
        if not (f["anon_can_execute"] and f["authenticated_can_execute"]):
            print(f"function {f['name']} has restricted execute; generator needs extending", file=sys.stderr)
            return 1

    # ---- triggers on public tables (verbatim)
    for t in ev["triggers"]:
        if t["schema"] == "public":
            w(t["definition"] + ";")
    w("")

    # ---- policies (verbatim expressions)
    def policy_sql(p: dict) -> str:
        roles = ", ".join(p["roles"])
        s = (f"create policy {ident(p['name'])} on {p['schema']}.{ident(p['table'])} "
             f"as {p['permissive'].lower()} for {p['command'].lower()} to {roles}")
        if p["using"] is not None:
            s += f"\n  using ({p['using']})"
        if p["with_check"] is not None:
            s += f"\n  with check ({p['with_check']})"
        return s + ";"

    for p in ev["policies"]:
        if p["schema"] == "public":
            w(policy_sql(p))
    w("")
    storage = [p for p in ev["policies"] if p["schema"] == "storage"]
    if storage:
        w("-- storage.objects policies: only when the platform storage schema exists.")
        w("do $storage$")
        w("begin")
        w("  if to_regclass('storage.objects') is null then")
        w("    raise notice 'baseline: storage.objects absent, storage policies skipped';")
        w("    return;")
        w("  end if;")
        for p in storage:
            w(f"  if not exists (select 1 from pg_policies where schemaname = 'storage' "
              f"and tablename = '{p['table']}' and policyname = '{p['name']}') then")
            w("    execute $p$" + policy_sql(p) + "$p$;")
            w("  end if;")
        w("end")
        w("$storage$;")
    w("")
    w("reset check_function_bodies;")
    w("reset search_path;")

    DST.write_text("\n".join(out) + "\n")
    print(f"wrote {DST.relative_to(ROOT)} ({len(out)} lines)")
    return 0


if __name__ == "__main__":
    sys.exit(main())
