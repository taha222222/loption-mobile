-- Same function as in the activity migration plus the phone checks
-- (marked "standalone migration").
create or replace function public.activity_daily_prepare()
returns trigger
language plpgsql set search_path = ''
as $$
declare
  today date;
  day_start timestamptz;
  day_end timestamptz;
begin
  if current_user in ('anon', 'authenticated') then
    if auth.uid() is null then
      raise exception 'not signed in' using errcode = '42501';
    end if;
    if tg_op = 'INSERT' then
      new.user_id := auth.uid();
    elsif new.user_id is distinct from old.user_id or new.local_date is distinct from old.local_date
          or new.source is distinct from old.source then
      raise exception 'activity day keys cannot change' using errcode = '22023';
    end if;
  end if;
  if not public.is_valid_time_zone(new.time_zone) then
    raise exception 'unknown time zone' using errcode = '22023';
  end if;
  today := (now() at time zone new.time_zone)::date;
  if new.local_date > today or new.local_date < today - 30 then
    raise exception 'activity can be synced for today and the previous 30 days only' using errcode = '22023';
  end if;
  -- standalone migration: phone measurements.
  if new.measured_from is not null then
    day_start := new.local_date::timestamp at time zone new.time_zone;
    day_end := (new.local_date + 1)::timestamp at time zone new.time_zone;
    if new.measured_from < day_start - interval '1 minute' or new.measured_to > day_end + interval '1 minute'
       or new.measured_to > now() + interval '5 minutes' then
      raise exception 'measurement window outside the day' using errcode = '22023';
    end if;
  end if;
  if new.source = 'device_motion' then
    if new.steps is not null and new.measured_from is not null
       and new.steps > 4 * extract(epoch from new.measured_to - new.measured_from) + 200 then
      raise exception 'implausible step count for the measured time' using errcode = '22023';
    end if;
    if new.distance_m is not null and (new.steps is null or new.distance_m > new.steps * 2.5 + 50) then
      raise exception 'implausible distance for the step count' using errcode = '22023';
    end if;
    if tg_op = 'UPDATE' and current_user in ('anon', 'authenticated') then
      -- A phone counter only grows during a day: never lower a stored day.
      if old.steps is not null and (new.steps is null or new.steps < old.steps) then
        new.steps := old.steps;
        new.distance_m := coalesce(greatest(old.distance_m, new.distance_m), old.distance_m);
      end if;
      if old.measured_from is not null then
        new.measured_from := least(old.measured_from, coalesce(new.measured_from, old.measured_from));
        new.measured_to := greatest(old.measured_to, coalesce(new.measured_to, old.measured_to));
      end if;
    end if;
  end if;
  new.synced_at := now();
  new.coverage := case when now() >= ((new.local_date + 1)::timestamp at time zone new.time_zone) then 'complete' else 'partial' end;
  if new.coverage <> 'complete'
     or (new.total_energy_kcal is not null and new.active_energy_kcal is not null
         and new.total_energy_kcal < new.active_energy_kcal) then
    new.total_energy_kcal := null;
  end if;
  return new;
end;
$$;
revoke all on function public.activity_daily_prepare() from public, anon, authenticated;

