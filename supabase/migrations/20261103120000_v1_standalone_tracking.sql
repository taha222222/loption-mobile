-- SECURITY INVOKER: the parent row is read with the caller's rights, so a
-- session or exercise of another customer is invisible and refused.
create function public.workout_gym_prepare()
returns trigger
language plpgsql set search_path = ''
as $$
begin
  if current_user in ('anon', 'authenticated') then
    if auth.uid() is null then
      raise exception 'not signed in' using errcode = '42501';
    end if;
    new.user_id := auth.uid();
  end if;
  if tg_table_name = 'workout_exercises' then
    if not exists (select 1 from public.workout_sessions w
                    where w.id = new.session_id and w.user_id = new.user_id and w.kind = 'gym') then
      raise exception 'gym session not found for this account' using errcode = '42501';
    end if;
    new.name := btrim(new.name);
  else
    if not exists (select 1 from public.workout_exercises e where e.id = new.exercise_id and e.user_id = new.user_id) then
      raise exception 'exercise not found for this account' using errcode = '42501';
    end if;
  end if;
  new.created_at := now();
  return new;
end;
$$;
revoke all on function public.workout_gym_prepare() from public, anon, authenticated;
create trigger trg_workout_exercises_prepare
  before insert on public.workout_exercises
  for each row execute function public.workout_gym_prepare();
create trigger trg_workout_sets_prepare
  before insert on public.workout_sets
  for each row execute function public.workout_gym_prepare();

-- Replaces the gym log of one session of the caller (idempotent: a retry
-- writes the same rows). p_exercises: [{name, category, sets: [{reps,
-- weight_kg, rest_seconds}]}], at most 30 exercises of 20 sets.
create function public.save_gym_log(p_client_session_id uuid, p_exercises jsonb)
returns integer
language plpgsql set search_path = ''
as $$
declare
  sid uuid;
  ex jsonb;
  st jsonb;
  eid uuid;
  i integer := 0;
  j integer;
begin
  if auth.uid() is null then
    raise exception 'not signed in' using errcode = '42501';
  end if;
  if jsonb_typeof(coalesce(p_exercises, 'null'::jsonb)) <> 'array' or jsonb_array_length(p_exercises) > 30 then
    raise exception 'invalid gym log' using errcode = '22023';
  end if;
  select w.id into sid from public.workout_sessions w
   where w.user_id = auth.uid() and w.client_session_id = p_client_session_id and w.kind = 'gym';
  if sid is null then
    raise exception 'gym session not found for this account' using errcode = '42501';
  end if;
  delete from public.workout_exercises where session_id = sid;
  for ex in select * from jsonb_array_elements(p_exercises) loop
    if jsonb_typeof(ex -> 'sets') is distinct from 'array' or jsonb_array_length(ex -> 'sets') > 20 then
      raise exception 'invalid gym log' using errcode = '22023';
    end if;
    insert into public.workout_exercises (session_id, position, name, category)
    values (sid, i, ex ->> 'name', ex ->> 'category') returning id into eid;
    j := 0;
    for st in select * from jsonb_array_elements(ex -> 'sets') loop
      insert into public.workout_sets (exercise_id, position, reps, weight_kg, rest_seconds)
      values (eid, j, (st ->> 'reps')::integer, (st ->> 'weight_kg')::numeric, (st ->> 'rest_seconds')::integer);
      j := j + 1;
    end loop;
    i := i + 1;
  end loop;
  return i;
end;
$$;
revoke all on function public.save_gym_log(uuid, jsonb) from public, anon;
grant execute on function public.save_gym_log(uuid, jsonb) to authenticated;

