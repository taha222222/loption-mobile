-- =====================================================================
-- L'OPTION V1 — standalone activity and calorie tracking: the phone itself
-- (iPhone Core Motion, Android hardware step counter) is the primary
-- activity source; Apple Health / Health Connect stay optional.
--
-- STATUS: proposal for review. NOT applied to any hosted database.
-- Depends on 20261030120000_v1_activity_tracking.sql.
-- Rollback: supabase/rollback/v1_standalone_tracking_rollback.sql (run it
-- BEFORE the activity rollback).
--
-- Role postgres only; one transaction with a deferred commit gate (same
-- pattern as Phase 1C). Refuses unless the Phase 1C monitor and every
-- function it replaces are exactly the activity-migration versions.
--
-- What this changes (no table is duplicated, no row is deleted)
--  1. activity_daily_totals, source 'device_motion' (= the phone's own
--     motion sensor, iPhone and Android): may carry a distance measured by
--     the phone (iPhone) and the measured window (first/last sample of the
--     day). The server checks the window lies inside the local day and is
--     not in the future, that the step count is physically possible for
--     the window (at most 4 steps per second) and the distance for the
--     steps (at most 2.5 m per step). A re-sync of a phone day never lowers
--     the stored count (sensor counters only grow during a day; a device
--     that lost its local history must not erase the day).
--  2. workout_sessions: steps counted by the phone during the session
--     (used to avoid counting a walk twice) and, for gym sessions, the
--     intensity chosen by the customer. MET values for gym: Compendium of
--     Physical Activities 2011, codes 02054 (light, 3.5), 02052 (moderate,
--     5.0) and 02050 (vigorous, 6.0). An estimate, never a measurement.
--  3. workout_exercises / workout_sets: the exercises, sets, repetitions,
--     weights and rest times of a gym session. Owner-only, attached to the
--     customer's own gym session (checked by trigger), replaced atomically
--     by save_gym_log() (SECURITY INVOKER: RLS applies).
--  4. nutrition_log_entries: manual meals (food from outside L'OPTION).
--     The customer enters a name and calories per portion; such an entry
--     is labelled entry_source 'manual'. Menu meals keep their calories
--     from public.meals (the trigger overwrites any client value).
--  5. Standalone daily energy budget, method 'bmr_plus_movement', used when
--     the phone measured steps and no health platform is connected:
--       budget = BMR x 1.1 (rest + digestion, thermic effect of food
--                ~10 %, Westerterp 2004)
--              + walking energy of the steps NOT taken during a recorded
--                walk/run (net cost 0.5 kcal per kg per km: horizontal term
--                of the ACSM walking equation, 0.1 mL O2/kg/m x 5 kcal/L)
--              + recorded workout energy (net MET estimate).
--     Distance: measured by the phone when available, else steps x stride
--     (0.415 x height, labelled estimated). Steps inside a walk/run are
--     taken from the session (phone count, else distance / stride, else a
--     typical cadence) and are not counted twice. The other methods
--     (platform_total, bmr_plus_active, tdee_baseline) are unchanged.
--
-- Phase 1C containment: the new owner-only policies are added to
-- containment_violations()'s reviewed lists (section 9, generated by
-- supabase/tools/generate_nutrition_monitor.py). Nothing else in the
-- monitor changes. The new fingerprint is recorded in
-- supabase/tests/postdeploy_verify_standalone_readonly.sql.
-- =====================================================================

