-- Same function as in the activity migration plus steps and gym intensity
-- (marked "standalone migration").
create or replace function public.workout_session_prepare()
returns trigger
language plpgsql set search_path = ''
as $$
declare
  span numeric;
  speed numeric;
  weight numeric;
begin
  if current_user in ('anon', 'authenticated') then
    if auth.uid() is null then
      raise exception 'not signed in' using errcode = '42501';
    end if;
    new.user_id := auth.uid();
  end if;
  if not public.is_valid_time_zone(new.time_zone) then
    raise exception 'unknown time zone' using errcode = '22023';
  end if;
  if new.ended_at > now() + interval '5 minutes' or new.started_at < now() - interval '31 days' then
    raise exception 'workouts can be saved for the last 30 days only' using errcode = '22023';
  end if;
  span := extract(epoch from new.ended_at - new.started_at);
  if new.active_seconds > span + 60 then
    raise exception 'active time is longer than the session' using errcode = '22023';
  end if;
  if new.source = 'app' then
    if new.provider_energy_kcal is not null then
      raise exception 'energy of an app workout is estimated by the server' using errcode = '22023';
    end if;
    if new.distance_source is distinct from 'gps' and new.distance_m is not null then
      raise exception 'an app workout distance comes from GPS' using errcode = '22023';
    end if;
  elsif new.distance_m is not null and new.distance_source <> 'provider' then
    raise exception 'an imported workout distance comes from the provider' using errcode = '22023';
  end if;
  -- standalone migration: at most 4 steps per second of active time.
  if new.steps is not null and new.steps > 4 * new.active_seconds + 50 then
    raise exception 'implausible step count for this workout' using errcode = '22023';
  end if;
  speed := case when new.distance_m is not null and new.distance_m > 0 then new.distance_m / new.active_seconds::numeric end;
  if speed is not null and speed > public.activity_max_speed(new.kind) then
    raise exception 'implausible distance for this workout' using errcode = '22023';
  end if;
  new.local_date := (new.started_at at time zone new.time_zone)::date;
  new.energy_kcal := null;
  new.met := null;
  new.weight_kg := null;
  new.energy_source := 'none';
  if new.source <> 'app' and new.provider_energy_kcal is not null then
    new.energy_kcal := new.provider_energy_kcal;
    new.energy_source := 'provider_measured';
  else
    select p.weight into weight from public.user_profiles p where p.user_id = new.user_id;
    new.met := case when new.kind = 'gym' and new.intensity is not null then public.activity_gym_met(new.intensity)
                    else public.activity_met(new.kind, case when speed is not null and new.distance_m >= 100 then speed end) end;
    if weight is not null and weight between 25 and 350 then
      -- Net energy above rest, comparable with a platform's "active energy".
      new.weight_kg := weight;
      new.energy_kcal := round((new.met - 1) * weight * new.active_seconds / 3600.0)::integer;
      new.energy_source := 'met_estimate';
    end if;
  end if;
  if new.source = 'app' then
    -- One app session at a time per customer.
    perform pg_advisory_xact_lock(hashtextextended('activity.workouts:' || new.user_id::text, 0));
    if exists (select 1 from public.workout_sessions w
                where w.user_id = new.user_id and w.source = 'app'
                  and w.client_session_id is distinct from new.client_session_id
                  and tstzrange(w.started_at, w.ended_at) && tstzrange(new.started_at, new.ended_at)) then
      raise exception 'workout overlaps another session' using errcode = '22023';
    end if;
  end if;
  new.created_at := now();
  return new;
end;
$$;
revoke all on function public.workout_session_prepare() from public, anon, authenticated;

