-- Walking stride (m) from height: 0.415 x height (rule of thumb used by
-- pedometer makers). NULL when the height is missing or out of range.
create function public.activity_stride_m(p_height_cm numeric)
returns numeric
language sql immutable set search_path = ''
as $$ select case when p_height_cm between 100 and 250 then round(0.415 * p_height_cm / 100.0, 3) end $$;
revoke all on function public.activity_stride_m(numeric) from public, anon;
grant execute on function public.activity_stride_m(numeric) to authenticated, service_role;

-- Net walking energy (kcal) of a distance: 0.5 kcal per kg per km (ACSM
-- walking equation, horizontal component). NULL without a valid weight.
create function public.activity_walk_kcal(p_distance_m numeric, p_weight_kg numeric)
returns integer
language sql immutable set search_path = ''
as $$
  select case when p_weight_kg between 25 and 350 and p_distance_m is not null and p_distance_m >= 0
              then round(0.5 * p_weight_kg * p_distance_m / 1000.0)::integer end
$$;
revoke all on function public.activity_walk_kcal(numeric, numeric) from public, anon;
grant execute on function public.activity_walk_kcal(numeric, numeric) to authenticated, service_role;

-- One method per day, never a sum of overlapping measures:
--   platform_total     the platform's total energy for a finished day
--   bmr_plus_active    BMR + the platform's active energy (it contains workouts)
--   bmr_plus_movement  BMR x 1.1 + the phone's movement energy (steps and
--                      recorded workouts, without double counting)
--   tdee_baseline      the TDEE estimate (BMR x habitual activity level)
-- An overload: the activity migration's 5-argument function is kept unchanged.
create function public.activity_energy_estimate(p_bmr integer, p_tdee integer, p_active integer, p_total integer,
                                                p_coverage text, p_movement integer)
returns table (estimate_kcal integer, method text)
language sql immutable set search_path = ''
as $$
  select case when p_total is not null and p_coverage = 'complete' and (p_bmr is null or p_total >= p_bmr) then p_total
              when p_active is not null and p_bmr is not null then p_bmr + p_active
              when p_movement is not null and p_bmr is not null then round(p_bmr * 1.1)::integer + p_movement
              else p_tdee end,
         case when p_total is not null and p_coverage = 'complete' and (p_bmr is null or p_total >= p_bmr) then 'platform_total'
              when p_active is not null and p_bmr is not null then 'bmr_plus_active'
              when p_movement is not null and p_bmr is not null then 'bmr_plus_movement'
              when p_tdee is not null then 'tdee_baseline' end
$$;
revoke all on function public.activity_energy_estimate(integer, integer, integer, integer, text, integer) from public, anon;
grant execute on function public.activity_energy_estimate(integer, integer, integer, integer, text, integer) to authenticated, service_role;

