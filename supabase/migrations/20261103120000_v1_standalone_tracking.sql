-- One row per day in [p_from, p_to] (at most 92 days), own data only (RLS).
-- The columns of the activity migration, unchanged in meaning, plus:
--   base_kcal            BMR x 1.1 for bmr_plus_movement, BMR for bmr_plus_active
--   step_kcal            walking energy of the steps outside recorded walks/runs
--   counted_workout_kcal workout energy counted in the budget (0 when the
--                        platform's active energy already contains it)
--   activity_kcal        energy of movement shown to the customer
--   active_minutes       minutes of recorded workouts (duplicates removed)
--   walk_distance_m      distance measured by the source, else steps x stride
--   walk_distance_estimated  true when walk_distance_m comes from the stride
--   measured_from/to     the phone's measured window that day
--   confidence           'measured' | 'estimated' | 'baseline'
create function public.activity_daily_summary(p_from date, p_to date, p_today date default null)
returns table (local_date date, entry_count integer, consumed_kcal integer, has_meal_log boolean,
               bmr_kcal integer, tdee_kcal integer, target_source text,
               activity_source text, steps integer, distance_m integer, active_energy_kcal integer,
               total_energy_kcal integer, coverage text, synced_at timestamptz,
               energy_estimate_kcal integer, energy_method text, remaining_kcal integer,
               workout_count integer, workout_seconds integer, workout_kcal integer, workout_kcal_estimated boolean,
               base_kcal integer, step_kcal integer, counted_workout_kcal integer, activity_kcal integer,
               active_minutes integer, walk_distance_m integer, walk_distance_estimated boolean,
               measured_from timestamptz, measured_to timestamptz, confidence text)
language sql stable set search_path = ''
as $$
  with days as (
    select d::date as local_date
      from generate_series(p_from, p_to, interval '1 day') d
     where p_from <= p_to and p_to - p_from <= 91
  ),
  meals as (
    select n.local_date, count(*)::integer as entry_count, sum(n.kcal)::integer as kcal
      from public.nutrition_log_entries n
     where n.user_id = auth.uid() and n.deleted_at is null and n.local_date between p_from and p_to
     group by n.local_date
  ),
  act as (
    select distinct on (a.local_date) a.*
      from public.activity_daily_totals a
     where a.user_id = auth.uid() and a.local_date between p_from and p_to
     order by a.local_date, (a.source = 'device_motion'), (a.coverage = 'complete') desc, a.synced_at desc
  ),
  cur as (
    select p.bmr_kcal, p.tdee_kcal, p.weight, p.height from public.user_profiles p where p.user_id = auth.uid()
  ),
  wx as (
    select x.*, (x.kind in ('walk', 'run') and x.source = 'app') as on_foot
      from public.activity_workouts(p_from, p_to) x
     where x.duplicate_of is null
  ),
  base as (
    select days.local_date, meals.entry_count, meals.kcal,
           coalesce(t.bmr_kcal, case when days.local_date = p_today then (select bmr_kcal from cur) end) as bmr,
           coalesce(t.tdee_kcal, case when days.local_date = p_today then (select tdee_kcal from cur) end) as tdee,
           case when t.user_id is not null then 'snapshot'
                when days.local_date = p_today and (select tdee_kcal from cur) is not null then 'current' end as target_source,
           coalesce((t.inputs ->> 'weight_kg')::numeric, case when days.local_date = p_today then (select weight from cur) end) as weight,
           coalesce((t.inputs ->> 'height_cm')::numeric, case when days.local_date = p_today then (select height from cur) end) as height,
           act.source, act.steps, act.distance_m, act.active_energy_kcal, act.total_energy_kcal, act.coverage, act.synced_at,
           act.measured_from, act.measured_to,
           (select count(*)::integer from wx where wx.local_date = days.local_date) as n,
           (select sum(wx.active_seconds)::integer from wx where wx.local_date = days.local_date) as secs,
           (select sum(wx.energy_kcal)::integer from wx where wx.local_date = days.local_date) as wkcal,
           (select bool_or(wx.energy_source = 'met_estimate') from wx where wx.local_date = days.local_date) as estimated,
           (select sum(wx.steps)::integer from wx where wx.local_date = days.local_date and wx.on_foot and wx.steps is not null) as wsteps_counted,
           (select sum(wx.distance_m)::numeric from wx where wx.local_date = days.local_date and wx.on_foot and wx.steps is null and wx.distance_m is not null) as wdist_uncounted,
           (select sum(wx.active_seconds * case wx.kind when 'run' then 2.7 else 1.8 end)::numeric from wx
             where wx.local_date = days.local_date and wx.on_foot and wx.steps is null and wx.distance_m is null) as wsteps_cadence
      from days
      left join meals on meals.local_date = days.local_date
      left join act on act.local_date = days.local_date
      left join public.nutrition_daily_targets t on t.user_id = auth.uid() and t.local_date = days.local_date
  ),
  mv as (
    select b.*,
           public.activity_stride_m(b.height) as stride,
           case when b.source = 'device_motion' and b.steps is not null then
             greatest(0, b.steps - round(coalesce(b.wsteps_counted, 0)
                                         + coalesce(b.wdist_uncounted / nullif(public.activity_stride_m(b.height), 0), 0)
                                         + coalesce(b.wsteps_cadence, 0)))::integer
           end as free_steps
      from base b
  ),
  mv2 as (
    select m.*,
           coalesce(m.distance_m::numeric, m.steps * m.stride) as walk_dist,
           case when m.free_steps is not null then
             public.activity_walk_kcal(case when m.distance_m is not null and m.steps > 0 then m.distance_m * m.free_steps::numeric / m.steps
                                            else m.free_steps * m.stride end, m.weight)
           end as step_kcal
      from mv m
  ),
  fin as (
    select m.*,
           case when m.step_kcal is not null then m.step_kcal + coalesce(m.wkcal, 0) end as movement,
           e.estimate_kcal, e.method
      from mv2 m
      cross join lateral public.activity_energy_estimate(m.bmr, m.tdee, m.active_energy_kcal, m.total_energy_kcal, m.coverage,
                                                         case when m.step_kcal is not null then m.step_kcal + coalesce(m.wkcal, 0) end) e
  )
  select f.local_date, coalesce(f.entry_count, 0), f.kcal, f.entry_count is not null,
         f.bmr, f.tdee, f.target_source,
         f.source, f.steps, f.distance_m, f.active_energy_kcal, f.total_energy_kcal, f.coverage, f.synced_at,
         f.estimate_kcal, f.method, f.estimate_kcal - coalesce(f.kcal, 0),
         coalesce(f.n, 0), coalesce(f.secs, 0), f.wkcal, coalesce(f.estimated, false),
         case f.method when 'bmr_plus_movement' then round(f.bmr * 1.1)::integer when 'bmr_plus_active' then f.bmr end,
         case when f.method = 'bmr_plus_movement' then f.step_kcal end,
         case when f.method = 'bmr_plus_movement' then coalesce(f.wkcal, 0) else 0 end,
         case f.method when 'bmr_plus_movement' then f.movement
                       when 'bmr_plus_active' then f.active_energy_kcal
                       when 'platform_total' then f.active_energy_kcal end,
         coalesce(f.secs, 0) / 60,
         round(f.walk_dist)::integer,
         f.distance_m is null and f.walk_dist is not null,
         f.measured_from, f.measured_to,
         case when f.method is null then null when f.method = 'platform_total' then 'measured'
              when f.method = 'tdee_baseline' then 'baseline' else 'estimated' end
    from fin f
   order by f.local_date
$$;
revoke all on function public.activity_daily_summary(date, date, date) from public, anon;
grant execute on function public.activity_daily_summary(date, date, date) to authenticated;

