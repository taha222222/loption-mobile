-- SECURITY INVOKER. Stamps owner and sync time, checks the date window
-- (today and the previous 30 days in the given time zone) and derives the
-- coverage: 'complete' only when the local day was over at sync time. A
-- total energy value for an unfinished day is dropped (it is not a daily
-- total), as is a total lower than the active energy.
create function public.activity_daily_prepare()
returns trigger
language plpgsql set search_path = ''
as $$
declare
  today date;
begin
  if current_user in ('anon', 'authenticated') then
    if auth.uid() is null then
      raise exception 'not signed in' using errcode = '42501';
    end if;
    if tg_op = 'INSERT' then
      new.user_id := auth.uid();
    elsif new.user_id is distinct from old.user_id or new.local_date is distinct from old.local_date
          or new.source is distinct from old.source then
      raise exception 'activity day keys cannot change' using errcode = '22023';
    end if;
  end if;
  if not public.is_valid_time_zone(new.time_zone) then
    raise exception 'unknown time zone' using errcode = '22023';
  end if;
  today := (now() at time zone new.time_zone)::date;
  if new.local_date > today or new.local_date < today - 30 then
    raise exception 'activity can be synced for today and the previous 30 days only' using errcode = '22023';
  end if;
  new.synced_at := now();
  new.coverage := case when now() >= ((new.local_date + 1)::timestamp at time zone new.time_zone) then 'complete' else 'partial' end;
  if new.coverage <> 'complete'
     or (new.total_energy_kcal is not null and new.active_energy_kcal is not null
         and new.total_energy_kcal < new.active_energy_kcal) then
    new.total_energy_kcal := null;
  end if;
  return new;
end;
$$;
revoke all on function public.activity_daily_prepare() from public, anon, authenticated;
create trigger trg_activity_daily_prepare
  before insert or update on public.activity_daily_totals
  for each row execute function public.activity_daily_prepare();

