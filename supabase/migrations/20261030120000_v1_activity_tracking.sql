-- Depends on 20261029120000_v1_nutrition_tracking_engagement.sql (and so on
-- Phase 1C revision 7, NOT READY FOR STAGING).
-- Rollback: supabase/rollback/v1_activity_tracking_rollback.sql (run it
-- BEFORE the nutrition rollback).
--
-- Role postgres only; one transaction with a deferred commit gate (same
-- pattern as Phase 1C). Refuses unless the Phase 1C monitor is exactly the
-- function installed by the nutrition migration and reports zero
-- violations.
--
-- What this adds
--  * activity_daily_totals: one row per customer, local date and source.
--    The app sends what the health platform reports for that day; the
--    server stamps the sync time, the owner and whether the day was over
--    when it was read (coverage). A partial day never carries a total
--    energy value. Health data is owner-only (RLS) and deleted with the
--    account; the customer can delete it (disconnect).
--  * workout_sessions: walks, runs, rides and gym sessions recorded in the
--    app or imported from the health platform. For a session recorded in
--    the app the client cannot send an energy value: the server estimates
--    it (MET x body weight x active time, labelled 'met_estimate'). An
--    imported session keeps the provider's measured value
--    ('provider_measured'). App sessions of one customer cannot overlap;
--    an app session and an imported one covering the same exercise are
--    paired by activity_workouts() so it is shown and counted once.
--  * Workouts never change the daily energy budget: the platform's daily
--    active energy already contains them (no double counting).
--  * activity_energy_estimate() / activity_daily_summary(): the daily
--    energy budget, one method per day (platform total energy for a
--    finished day, else BMR + platform active energy, else the TDEE
--    baseline), consumed calories, remaining calories (negative when over),
--    steps, distance, workouts. Read-only, SECURITY INVOKER.
--  * Meals logged from an order: only once the order was received
--    (status 'delivered' or 'served'). Replaces the nutrition log trigger
--    with that one extra check; the rollback restores the original.
--
-- Phase 1C containment: the new client policies are added to
-- containment_violations()'s reviewed lists (section 9, generated by
-- supabase/tools/generate_nutrition_monitor.py). Nothing else in the
-- monitor changes. The postcondition requires zero violations. The new
-- fingerprint is recorded in
-- supabase/tests/postdeploy_verify_activity_readonly.sql.
-- =====================================================================

