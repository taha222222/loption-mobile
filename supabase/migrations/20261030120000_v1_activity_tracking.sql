-- 2. Workout sessions
-- ---------------------------------------------------------------------
-- MET values (energy cost relative to rest), approximate tiers from the
-- Compendium of Physical Activities (Ainsworth et al., 2011) by average
-- speed (m/s) where a distance is known. Pending review by the owner.
create function public.activity_met(p_kind text, p_speed_mps numeric)
returns numeric
language sql immutable set search_path = ''
as $$
  select case p_kind
    when 'walk' then case when p_speed_mps is null then 3.5 when p_speed_mps < 0.9 then 2.0 when p_speed_mps < 1.12 then 2.8
                          when p_speed_mps < 1.56 then 3.5 when p_speed_mps < 1.79 then 4.3 else 5.0 end
    when 'run' then case when p_speed_mps is null then 7.0 when p_speed_mps < 1.95 then 6.0 when p_speed_mps < 2.42 then 8.3
                         when p_speed_mps < 2.92 then 9.8 when p_speed_mps < 3.36 then 11.0 when p_speed_mps < 3.81 then 11.8
                         when p_speed_mps < 4.25 then 12.8 else 14.5 end
    when 'cycle' then case when p_speed_mps is null then 7.5 when p_speed_mps < 4.47 then 4.0 when p_speed_mps < 5.36 then 6.8
                           when p_speed_mps < 6.26 then 8.0 when p_speed_mps < 7.15 then 10.0 else 12.0 end
    when 'gym' then 3.5
  end
$$;
revoke all on function public.activity_met(text, numeric) from public, anon;
grant execute on function public.activity_met(text, numeric) to authenticated, service_role;

-- Fastest plausible average speed (m/s) per kind; a faster distance is refused.
create function public.activity_max_speed(p_kind text)
returns numeric
language sql immutable set search_path = ''
as $$ select case p_kind when 'walk' then 3.5 when 'run' then 7.0 when 'cycle' then 25.0 else 0 end::numeric $$;
revoke all on function public.activity_max_speed(text) from public, anon;
grant execute on function public.activity_max_speed(text) to authenticated, service_role;

