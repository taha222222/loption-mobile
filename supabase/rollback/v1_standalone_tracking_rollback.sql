create or replace function public.activity_daily_prepare()
returns trigger
language plpgsql set search_path = ''
as $$
declare
  today date;
begin
  if current_user in ('anon', 'authenticated') then
    if auth.uid() is null then
      raise exception 'not signed in' using errcode = '42501';
    end if;
    if tg_op = 'INSERT' then
      new.user_id := auth.uid();
    elsif new.user_id is distinct from old.user_id or new.local_date is distinct from old.local_date
          or new.source is distinct from old.source then
      raise exception 'activity day keys cannot change' using errcode = '22023';
    end if;
  end if;
  if not public.is_valid_time_zone(new.time_zone) then
    raise exception 'unknown time zone' using errcode = '22023';
  end if;
  today := (now() at time zone new.time_zone)::date;
  if new.local_date > today or new.local_date < today - 30 then
    raise exception 'activity can be synced for today and the previous 30 days only' using errcode = '22023';
  end if;
  new.synced_at := now();
  new.coverage := case when now() >= ((new.local_date + 1)::timestamp at time zone new.time_zone) then 'complete' else 'partial' end;
  if new.coverage <> 'complete'
     or (new.total_energy_kcal is not null and new.active_energy_kcal is not null
         and new.total_energy_kcal < new.active_energy_kcal) then
    new.total_energy_kcal := null;
  end if;
  return new;
end;
$$;
create or replace function public.workout_session_prepare()
returns trigger
language plpgsql set search_path = ''
as $$
declare
  span numeric;
  speed numeric;
  weight numeric;
begin
  if current_user in ('anon', 'authenticated') then
    if auth.uid() is null then
      raise exception 'not signed in' using errcode = '42501';
    end if;
    new.user_id := auth.uid();
  end if;
  if not public.is_valid_time_zone(new.time_zone) then
    raise exception 'unknown time zone' using errcode = '22023';
  end if;
  if new.ended_at > now() + interval '5 minutes' or new.started_at < now() - interval '31 days' then
    raise exception 'workouts can be saved for the last 30 days only' using errcode = '22023';
  end if;
  span := extract(epoch from new.ended_at - new.started_at);
  if new.active_seconds > span + 60 then
    raise exception 'active time is longer than the session' using errcode = '22023';
  end if;
  if new.source = 'app' then
    if new.provider_energy_kcal is not null then
      raise exception 'energy of an app workout is estimated by the server' using errcode = '22023';
    end if;
    if new.distance_source is distinct from 'gps' and new.distance_m is not null then
      raise exception 'an app workout distance comes from GPS' using errcode = '22023';
    end if;
  elsif new.distance_m is not null and new.distance_source <> 'provider' then
    raise exception 'an imported workout distance comes from the provider' using errcode = '22023';
  end if;
  speed := case when new.distance_m is not null and new.distance_m > 0 then new.distance_m / new.active_seconds::numeric end;
  if speed is not null and speed > public.activity_max_speed(new.kind) then
    raise exception 'implausible distance for this workout' using errcode = '22023';
  end if;
  new.local_date := (new.started_at at time zone new.time_zone)::date;
  new.energy_kcal := null;
  new.met := null;
  new.weight_kg := null;
  new.energy_source := 'none';
  if new.source <> 'app' and new.provider_energy_kcal is not null then
    new.energy_kcal := new.provider_energy_kcal;
    new.energy_source := 'provider_measured';
  else
    select p.weight into weight from public.user_profiles p where p.user_id = new.user_id;
    new.met := public.activity_met(new.kind, case when speed is not null and new.distance_m >= 100 then speed end);
    if weight is not null and weight between 25 and 350 then
      -- Net energy above rest, comparable with a platform's "active energy".
      new.weight_kg := weight;
      new.energy_kcal := round((new.met - 1) * weight * new.active_seconds / 3600.0)::integer;
      new.energy_source := 'met_estimate';
    end if;
  end if;
  if new.source = 'app' then
    -- One app session at a time per customer.
    perform pg_advisory_xact_lock(hashtextextended('activity.workouts:' || new.user_id::text, 0));
    if exists (select 1 from public.workout_sessions w
                where w.user_id = new.user_id and w.source = 'app'
                  and w.client_session_id is distinct from new.client_session_id
                  and tstzrange(w.started_at, w.ended_at) && tstzrange(new.started_at, new.ended_at)) then
      raise exception 'workout overlaps another session' using errcode = '22023';
    end if;
  end if;
  new.created_at := now();
  return new;
end;
$$;
create or replace function public.nutrition_log_entry_prepare()
returns trigger
language plpgsql set search_path = ''
as $$
declare
  m record;
  oi record;
  today date;
  already numeric;
begin
  if current_user in ('anon', 'authenticated') then
    if auth.uid() is null then
      raise exception 'not signed in' using errcode = '42501';
    end if;
    new.user_id := auth.uid();
  end if;
  if not public.is_valid_time_zone(new.time_zone) then
    raise exception 'unknown time zone' using errcode = '22023';
  end if;
  today := (now() at time zone new.time_zone)::date;
  if new.local_date > today or new.local_date < today - 6 then
    raise exception 'meals can be logged for today and the previous 6 days only' using errcode = '22023';
  end if;
  if new.meal_id is null then
    raise exception 'a meal is required' using errcode = '22023';
  end if;
  select name, calories, protein, carbs, fat into m from public.meals where id = new.meal_id;
  if not found then
    raise exception 'unknown meal' using errcode = '22023';
  end if;
  if m.calories is null or m.calories <= 0 then
    raise exception 'this meal has no reliable calorie value' using errcode = '22023';
  end if;
  if new.order_item_id is not null then
    select i.meal_id, i.quantity, o.status into oi
      from public.order_items i join public.orders o on o.id = i.order_id
     where i.id = new.order_item_id and o.user_id = new.user_id;
    if not found then
      raise exception 'order item not found for this account' using errcode = '42501';
    end if;
    -- activity migration: an order counts only once it was received.
    if not public.order_received(oi.status) then
      raise exception 'this order has not been delivered yet' using errcode = '22023';
    end if;
    if oi.meal_id is distinct from new.meal_id then
      raise exception 'order item and meal do not match' using errcode = '22023';
    end if;
    -- Serialise concurrent logs of the same order item.
    perform pg_advisory_xact_lock(hashtextextended('nutrition.order_item:' || new.order_item_id::text, 0));
    select coalesce(sum(servings), 0) into already from public.nutrition_log_entries
     where order_item_id = new.order_item_id and deleted_at is null;
    if already + new.servings > oi.quantity then
      raise exception 'more servings logged than were ordered' using errcode = '22023';
    end if;
  end if;
  new.meal_name := m.name;
  new.kcal_per_serving := m.calories;
  new.kcal := round(m.calories * new.servings)::integer;
  new.protein_g := case when m.protein is null then null else round(m.protein * new.servings, 1) end;
  new.carbs_g := case when m.carbs is null then null else round(m.carbs * new.servings, 1) end;
  new.fat_g := case when m.fat is null then null else round(m.fat * new.servings, 1) end;
  new.logged_at := now();
  new.deleted_at := null;
  return new;
end;
$$;
create or replace function public.activity_workouts(p_from date, p_to date)
returns table (id uuid, source text, kind text, started_at timestamptz, ended_at timestamptz, active_seconds integer,
               local_date date, time_zone text, distance_m integer, distance_source text, energy_kcal integer,
               energy_source text, met numeric, duplicate_of uuid)
language sql stable set search_path = ''
as $$
  with s as (
    select w.*,
           case when w.source <> 'app' and w.energy_source = 'provider_measured' then 3 when w.source <> 'app' then 2 else 1 end as prio,
           extract(epoch from w.ended_at - w.started_at) as span
      from public.workout_sessions w
     where w.user_id = auth.uid() and p_from <= p_to and p_to - p_from <= 91
       and w.local_date between p_from - 1 and p_to + 1
  )
  select s.id, s.source, s.kind, s.started_at, s.ended_at, s.active_seconds, s.local_date, s.time_zone, s.distance_m,
         s.distance_source, s.energy_kcal, s.energy_source, s.met,
         (select t.id from s t
           where t.id <> s.id and t.kind = s.kind and t.source <> s.source
             and (t.prio > s.prio or (t.prio = s.prio and t.id < s.id))
             and extract(epoch from least(t.ended_at, s.ended_at) - greatest(t.started_at, s.started_at)) >= 0.5 * least(t.span, s.span)
           order by t.prio desc, t.id limit 1)
    from s
   where s.local_date between p_from and p_to
   order by s.started_at
$$;
create or replace function public.activity_daily_summary(p_from date, p_to date, p_today date default null)
returns table (local_date date, entry_count integer, consumed_kcal integer, has_meal_log boolean,
               bmr_kcal integer, tdee_kcal integer, target_source text,
               activity_source text, steps integer, distance_m integer, active_energy_kcal integer,
               total_energy_kcal integer, coverage text, synced_at timestamptz,
               energy_estimate_kcal integer, energy_method text, remaining_kcal integer,
               workout_count integer, workout_seconds integer, workout_kcal integer, workout_kcal_estimated boolean)
language sql stable set search_path = ''
as $$
  with days as (
    select d::date as local_date
      from generate_series(p_from, p_to, interval '1 day') d
     where p_from <= p_to and p_to - p_from <= 91
  ),
  meals as (
    select n.local_date, count(*)::integer as entry_count, sum(n.kcal)::integer as kcal
      from public.nutrition_log_entries n
     where n.user_id = auth.uid() and n.deleted_at is null and n.local_date between p_from and p_to
     group by n.local_date
  ),
  act as (
    select distinct on (a.local_date) a.*
      from public.activity_daily_totals a
     where a.user_id = auth.uid() and a.local_date between p_from and p_to
     order by a.local_date, (a.source = 'device_motion'), (a.coverage = 'complete') desc, a.synced_at desc
  ),
  cur as (
    select p.bmr_kcal, p.tdee_kcal from public.user_profiles p where p.user_id = auth.uid()
  ),
  w as (
    select x.local_date, count(*)::integer as n, sum(x.active_seconds)::integer as secs,
           sum(x.energy_kcal)::integer as kcal, bool_or(x.energy_source = 'met_estimate') as estimated
      from public.activity_workouts(p_from, p_to) x
     where x.duplicate_of is null
     group by x.local_date
  ),
  base as (
    select days.local_date, meals.entry_count, meals.kcal,
           coalesce(t.bmr_kcal, case when days.local_date = p_today then (select bmr_kcal from cur) end) as bmr,
           coalesce(t.tdee_kcal, case when days.local_date = p_today then (select tdee_kcal from cur) end) as tdee,
           case when t.user_id is not null then 'snapshot'
                when days.local_date = p_today and (select tdee_kcal from cur) is not null then 'current' end as target_source,
           act.source, act.steps, act.distance_m, act.active_energy_kcal, act.total_energy_kcal, act.coverage, act.synced_at,
           w.n, w.secs, w.kcal as wkcal, w.estimated
      from days
      left join meals on meals.local_date = days.local_date
      left join act on act.local_date = days.local_date
      left join public.nutrition_daily_targets t on t.user_id = auth.uid() and t.local_date = days.local_date
      left join w on w.local_date = days.local_date
  )
  select b.local_date, coalesce(b.entry_count, 0), b.kcal, b.entry_count is not null,
         b.bmr, b.tdee, b.target_source,
         b.source, b.steps, b.distance_m, b.active_energy_kcal, b.total_energy_kcal, b.coverage, b.synced_at,
         e.estimate_kcal, e.method, e.estimate_kcal - coalesce(b.kcal, 0),
         coalesce(b.n, 0), coalesce(b.secs, 0), b.wkcal, coalesce(b.estimated, false)
    from base b
    cross join lateral public.activity_energy_estimate(b.bmr, b.tdee, b.active_energy_kcal, b.total_energy_kcal, b.coverage) e
   order by b.local_date
$$;
