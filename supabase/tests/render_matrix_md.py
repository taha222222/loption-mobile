#!/usr/bin/env python3
"""Render docs/v1/PHASE1C_POLICY_GRANT_MATRIX.md from two outputs of
supabase/tests/phase1c_matrix.sql (BEFORE and AFTER the migration).

Usage: render_matrix_md.py MATRIX_BEFORE.txt MATRIX_AFTER.txt OUT.md
Produce the inputs with: KEEP_OUTPUT=<dir> supabase/tests/run_phase1c.sh
(files matrix_before.txt and matrix_after.txt).
"""
import sys


def sections(path):
    out, cur = {}, None
    for line in open(path):
        line = line.rstrip("\n")
        if line.startswith("## "):
            cur = line[3:].split(":")[0].strip()
            out[cur] = []
        elif cur and line.strip():
            out[cur].append([c.strip() for c in line.split(" | ")])
    return out


def esc(s):
    return s.replace("|", "\\|")


def main():
    before, after = sections(sys.argv[1]), sections(sys.argv[2])
    md = []
    w = md.append
    w("# Phase 1C — policy, grant and function matrix (before / after)")
    w("")
    w("Generated by `supabase/tests/render_matrix_md.py` from `supabase/tests/phase1c_matrix.sql`.")
    w("The inputs come from `supabase/tests/run_phase1c.sh`: scenario A (BEFORE) and scenario B (AFTER).")
    w("")
    w("**Source: local disposable databases.**")
    w("- Image: `supabase/postgres:17.6.1.178`.")
    w("- BEFORE is the staging schema rebuilt from the 2026-10-15 catalog evidence. It is proven identical in every compared section.")
    w("- **This is not a reading of live staging.** Run `supabase/tests/preflight_staging_readonly.sql` on staging to confirm that it still matches.")
    w("")

    # ---- policies
    pb = {(r[0], r[1]): r for r in before.get("policies (public)", [])}
    pa = {(r[0], r[1]): r for r in after.get("policies (public)", [])}
    removed = sorted(set(pb) - set(pa))
    added = sorted(set(pa) - set(pb))
    kept = sorted(set(pa) & set(pb))
    w(f"## 1. Row-level security policies (public schema)")
    w("")
    w(f"Before: {len(pb)} policies. After: {len(pa)}. Removed: {len(removed)}. Added: {len(added)}. Unchanged: {len(kept)}.")
    w("")
    w("### Removed")
    w("| Table | Policy | Cmd | Roles | USING | WITH CHECK |")
    w("|---|---|---|---|---|---|")
    for k in removed:
        r = pb[k]
        w(f"| {r[0]} | {esc(r[1])} | {r[2]} | {r[3]} | `{esc(r[4])}` | `{esc(r[5])}` |")
    w("")
    w("### Added")
    w("| Table | Policy | Cmd | Roles | USING | WITH CHECK |")
    w("|---|---|---|---|---|---|")
    for k in added:
        r = pa[k]
        w(f"| {r[0]} | {esc(r[1])} | {r[2]} | {r[3]} | `{esc(r[4])}` | `{esc(r[5])}` |")
    w("")
    w("### Unchanged")
    w("| Table | Policy | Cmd | USING | WITH CHECK |")
    w("|---|---|---|---|---|")
    for k in kept:
        r = pa[k]
        changed = " (**changed**)" if pa[k] != pb[k] else ""
        w(f"| {r[0]} | {esc(r[1])}{changed} | {r[2]} | `{esc(r[4])}` | `{esc(r[5])}` |")
    w("")

    # ---- table privileges
    tb = {r[0]: r for r in before.get("table privileges (public)", [])}
    ta = {r[0]: r for r in after.get("table privileges (public)", [])}
    w("## 2. Table privileges for client roles")
    w("")
    w("Key: s = select, i = insert, u = update, d = delete, t = truncate, r = references, g = trigger. A dash (-) means none.")
    w("")
    w("RLS still applies on top of these grants. Where `authenticated` keeps a write grant, the only write policy is the staff-admin policy, plus the service role.")
    w("")
    w("| Table | anon before | anon after | authenticated before | authenticated after |")
    w("|---|---|---|---|---|")
    for t in sorted(set(tb) | set(ta)):
        b = tb.get(t, [t, "(absent)", "(absent)"])
        a = ta.get(t, [t, "(absent)", "(absent)"])
        mark = "" if b[1:] == a[1:] else " ⟵"
        w(f"| {t}{mark} | {b[1]} | {a[1]} | {b[2]} | {a[2]} |")
    w("")

    # ---- column privileges
    cb = {r[0]: r[1] for r in before.get("column UPDATE privilege for authenticated on sensitive columns", [])}
    ca = {r[0]: r[1] for r in after.get("column UPDATE privilege for authenticated on sensitive columns", [])}
    w("## 3. Column UPDATE privilege for `authenticated` on sensitive columns")
    w("")
    w("| Column | Before | After |")
    w("|---|---|---|")
    for c in sorted(set(cb) | set(ca)):
        w(f"| {c} | {cb.get(c, '-')} | {ca.get(c, '-')} |")
    w("")
    w("`orders.total` and `orders.payment_method` stay `t` at the grant level because admins act through the `authenticated` role. RLS has no UPDATE policy on `orders` for customers or drivers; tests T04, T05 and T06d check this.")
    w("")

    # ---- functions
    fb = {r[0]: r for r in before.get("functions (public)", [])}
    fa = {r[0]: r for r in after.get("functions (public)", [])}
    w("## 4. Functions (public schema)")
    w("")
    w("| Function | SECURITY DEFINER | config before → after | anon exec before → after | authenticated exec before → after |")
    w("|---|---|---|---|---|")
    for f in sorted(set(fb) | set(fa)):
        b = fb.get(f, [f, "", "(absent)", "-", "-"])
        a = fa.get(f, [f, "", "(absent)", "-", "-"])
        sd = a[1] if f in fa else b[1]
        w(f"| `{f}` | {sd} | {esc(b[2])} → {esc(a[2])} | {b[3]} → {a[3]} | {b[4]} → {a[4]} |")
    w("")

    # ---- triggers / constraints / default privileges
    for title, key in (("5. Triggers (public)", "triggers (public, non-internal)"),
                       ("6. Check constraints on `drivers`", "check constraints on drivers"),
                       ("7. Default privileges of the migration role `postgres`", "default privileges (migration role postgres)")):
        w(f"## {title}")
        w("")
        w("**Before**")
        w("```")
        w("\n".join(" | ".join(r) for r in before.get(key, [])) or "(none)")
        w("```")
        w("**After**")
        w("```")
        w("\n".join(" | ".join(r) for r in after.get(key, [])) or "(none)")
        w("```")
        w("")
    w("The `storage` schema defaults are platform-managed and outside this migration (see the plan, *Residual risks*).")
    open(sys.argv[3], "w").write("\n".join(md) + "\n")


if __name__ == "__main__":
    main()
